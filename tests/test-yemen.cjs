const {chromium}=require('playwright');
const {pathToFileURL}=require('url');
const path=require('path');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
 const page=await browser.newPage({viewport:{width:1440,height:900},reducedMotion:'reduce'}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.route('https://lh3.googleusercontent.com/**',r=>r.abort());
 const url=pathToFileURL(path.join(__dirname,'..','index.html')).href;
 await page.goto(url);
 await page.evaluate(()=>localStorage.setItem('surge.demo.v1',JSON.stringify({theme:'light',selectedLocation:'الرياض',cart:[{id:'headphones',qty:1,color:'أسود مطفي',edition:'إصدار برو مع حقيبة السفر'},{id:'oud',qty:1,color:'',edition:''}]})));
 await page.reload();
 if(!(await page.locator('.location').innerText()).includes('المكلا'))errors.push('saved delivery migration');
 if((await page.locator('.product-card .price').first().innerText()).includes('ر.ي')===false)errors.push('product currency');
 if((await page.locator('.header').evaluate(e=>getComputedStyle(e).backgroundImage))==='none')errors.push('light header tint');
 if((await page.locator('footer').evaluate(e=>getComputedStyle(e).backgroundImage))==='none')errors.push('light footer tint');
 await page.setViewportSize({width:320,height:850});
 if(!(await page.locator('.location').isVisible()))errors.push('mobile location hidden');
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))errors.push('mobile overflow');
 await page.setViewportSize({width:1440,height:900});
 await page.locator('[data-action=location]').click();await page.locator('[data-action=choose-location][data-id="عدن"]').click();await page.reload();
 if(!(await page.locator('.location').innerText()).includes('عدن'))errors.push('new delivery location did not persist');
 await page.locator('[data-action=location]').click();await page.locator('[data-action=choose-location][data-id="المكلا"]').click();
 await page.goto(url+'#cart');
 if(await page.locator('.cart-item').count()!==2)errors.push('cart lost during migration');
 await page.locator('#coupon input').fill('SURGE10');await page.locator('#coupon button').first().click();
 const cartSummary=await page.locator('.summary-total').innerText();
 if(!cartSummary.includes('ر.ي')||cartSummary.includes('ر.س'))errors.push('cart currency');
 await page.goto(url+'#checkout');
 if(await page.locator('.summary-total').innerText()!==cartSummary)errors.push('cart and checkout totals differ');
 await page.locator('[name=name]').fill('أحمد التجريبي');await page.locator('[name=address]').fill('المكلا، حي السلام، شارع تجريبي');
 await page.locator('[name=phone]').fill('0501234567');await page.locator('#checkout-form button[type=submit]').click();
 if(!(await page.locator('[data-error=phone]').innerText()).includes('يمني'))errors.push('Yemeni phone validation');
 await page.locator('[name=phone]').fill('+967 ٧٧١٢٣٤٥٦٧');await page.locator('#checkout-form button[type=submit]').click();
 await page.waitForURL('**#success?id=*');
 if(!(await page.locator('.panel').innerText()).includes('ر.ي'))errors.push('order currency');
 await page.locator('[data-action=theme]').first().click();
 if((await page.locator('.header').evaluate(e=>getComputedStyle(e).backgroundImage))!=='none')errors.push('dark header tint changed');
 if((await page.locator('footer').evaluate(e=>getComputedStyle(e).backgroundImage))!=='none')errors.push('dark footer tint changed');
 const darkSurfaces=await page.evaluate(()=>['body','.header','footer'].map(selector=>getComputedStyle(document.querySelector(selector)).backgroundColor));
 if(darkSurfaces.join('|')!=='rgb(16, 23, 19)|rgb(16, 23, 19)|rgb(21, 31, 25)')errors.push('dark reference surfaces');
 if(errors.length)throw new Error(errors.join(', '));
 console.log('PASS Yemeni currency, Mukalla migration, mobile location, totals, checkout phone, and light/dark surfaces');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
